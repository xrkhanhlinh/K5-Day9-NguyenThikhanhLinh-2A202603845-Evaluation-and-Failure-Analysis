"""Explain overlapping M5/M6 blockers without changing the release spec or reports.

Run from src/: python -m scripts.check_checkpoint_evidence
Requires the reports generated by scripts.check_advanced.
"""
import hashlib
import json
from pathlib import Path
import subprocess
import sys

from lab8.console import utf8_stdio
from lab9 import gate, stats
from lab9.eval import load_spec, per_item


def main():
    utf8_stdio()
    spec_path = Path("config/metric_spec_v2.yaml")
    spec_bytes = spec_path.read_bytes()
    spec = load_spec(spec_path)
    base = json.loads(Path("reports/baseline_v2.json").read_text(encoding="utf-8"))
    assert not gate.check(base, base, spec, spec)[0]
    result = {"eval_set_sha": base["manifest"]["eval_set_sha"],
              "spec_sha256": hashlib.sha256(spec_bytes).hexdigest(), "cases": {}}
    floors = {m["id"]: m.get("threshold", {}).get("min") for m in spec["metrics"]}
    for name in ("slice_regression", "flaky_regression"):
        path = Path(f"reports/eval_{name}_v2.json")
        report = json.loads(path.read_text(encoding="utf-8"))
        blocked, _ = gate.check(report, base, spec, spec)
        assert blocked and "integrity" not in blocked
        a, b = per_item(report, "pass_rate"), per_item(base, "pass_rate")
        keys = sorted(a)
        delta, low, high = stats.paired_bootstrap([a[k] for k in keys], [b[k] for k in keys])
        case = {"report": path.as_posix(), "run_id": report["run_id"],
                "report_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                "pass_rate": report["metrics"]["pass_rate"], "pass_rate_min": floors["pass_rate"],
                "pass_rate_floor_pass": report["metrics"]["pass_rate"] >= floors["pass_rate"],
                "global_pass_rate_blocked": "pass_rate" in blocked,
                "paired_ci": {"delta": delta, "low": low, "high": high},
                "pass_hat_5": report["metrics"]["pass_hat_5"], "pass_hat_5_min": floors["pass_hat_5"],
                "blocked": blocked}
        assert case["pass_rate_floor_pass"]
        if name == "slice_regression":
            assert "pass_rate" not in blocked and high >= 0
            assert "slice:money_movement/pass_rate" in blocked
        else:
            assert "pass_hat_5" in blocked
        result["cases"][name] = case
    tests = ["tests/test_lab9_advanced_integrity.py::test_generic_slice_catches_regression_hidden_by_global_mean_and_ci",
             "tests/test_lab9_advanced_integrity.py::test_reliability_blocks_even_when_global_mean_improves"]
    command = [sys.executable, "-B", "-m", "pytest", "-q", "-o", "addopts=", *tests]
    completed = subprocess.run(command, capture_output=True, text=True, encoding="utf-8")
    print(completed.stdout, end="")
    if completed.returncode:
        print(completed.stderr)
        return completed.returncode
    result["independent_tests"] = {"node_ids": tests, "exit": completed.returncode,
                                   "stdout": completed.stdout, "stderr": completed.stderr}
    assert spec_path.read_bytes() == spec_bytes, "release spec must remain unchanged"
    result["passed"] = True
    Path("reports/checkpoint_evidence.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2, allow_nan=False), encoding="utf-8")
    rows = []
    for name, case in result["cases"].items():
        ci = case["paired_ci"]
        rows.append(f"| {name} | {case['pass_rate']} | {case['pass_rate_min']} | "
                    f"[{ci['low']:+.3f}, {ci['high']:+.3f}] | {case['global_pass_rate_blocked']} | "
                    f"{case['pass_hat_5']} | {', '.join(case['blocked'])} |")
    document = f"""# Đối chiếu checkpoint M5/M6

Tài liệu được sinh bởi `python -m scripts.check_checkpoint_evidence` từ các report đánh giá thực; số liệu gốc ở `src/reports/checkpoint_evidence.json`. Eval-set SHA `{result['eval_set_sha']}`, metric spec {spec['metric_spec_version']}, SHA-256 spec `{result['spec_sha256']}`. Script chỉ đọc spec và report, kiểm tra gate hiện tại rồi chạy hai test độc lập.

| Variant | pass_rate | Sàn global | CI Δ global | Global pass_rate chặn? | pass_hat_5 | Tất cả blocker của gate |
|---|---|---|---|---|---|---|
{chr(10).join(rows)}

## Cách đối chiếu với CHECKPOINTS.md

- M5: global `pass_rate` qua cả sàn và paired CI, còn slice `money_movement` chặn regression. Spec hiện có thêm metric proposal và slice adversarial chặn cùng lỗi; vì vậy không khẳng định “chỉ money_movement” trên toàn bộ spec mở rộng. Đây là kiểm tra mạnh hơn ở những metric bổ sung, không phải lý do nới ngưỡng đã commit.
- M6: `flaky_regression` qua sàn trung bình 0,85 nhưng `pass_hat_5` thấp hơn sàn reliability 0,85. Trên năm seed công khai, CI global cũng chặn; kết quả của một tập seed cố định không chứng minh global mean luôn phát hiện được lỗi hiếm.
- Ratchet vẫn giữ nguyên tất cả metric, blocking flag, sàn và quy tắc CI. Không đổi variant, trap hoặc dữ liệu để tạo kết quả mong muốn.

## Kiểm tra độc lập

1. `test_generic_slice_catches_regression_hidden_by_global_mean_and_ci`: global gate qua nhưng một slice dùng tên mới chặn. Chứng minh slice gate hoạt động độc lập với các metric proposal/reply.
2. `test_reliability_blocks_even_when_global_mean_improves`: baseline tự so với nó được cho qua; candidate có trung bình tốt hơn baseline nhưng reliability giảm và chỉ `pass_hat_5` chặn trong fixture test.

Hai test dùng dữ liệu tổng hợp tách khỏi dataset phát hành; không phải run agent hoặc kết quả held-out của giảng viên.

```text
{completed.stdout.strip()}
```

CI chạy lại script này sau khi sinh mới toàn bộ report Advanced. Kết quả cho thấy vai trò riêng của slice/reliability và giải thích rõ phần chồng lấp của các blocker trên fixture công khai. Xem [eval card](eval_card.md) cho A/A, mutation, traps và giới hạn cỡ mẫu.
"""
    Path("../docs/checkpoint_review.md").write_text(document, encoding="utf-8")
    print("Checkpoint evidence PASS: independent slice/reliability tests; release thresholds unchanged.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
